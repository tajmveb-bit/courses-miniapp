export function getConsciousnessNumber(id: number): ConsciousnessNumber | undefined {
  return consciousnessNumbers.find((n) => n.id === id);
}

// Digital root of the day of birth only — month and year don't matter for this number.
export function calculateConsciousnessNumber(day: number): number {
  let n = day;
  while (n > 9) {
    n = String(n)
      .split("")
      .reduce((sum, digit) => sum + Number(digit), 0);
  }
  return n;
}

// Шаг 3 протокола «Сайфер» — обратный ход, свой для каждой группы чисел.
export interface ProtocolStep3 {
  group: string;
  reaction: string;
  instead: string;
}

const PROTOCOL_STEP3: ProtocolStep3[] = [
  { group: "1 · 8 · 9", reaction: "хочется давить и повышать голос", instead: "сбавь тон, спроси мнение другого или уйди в движение" },
  { group: "2 · 5 · 6", reaction: "хочется обидеться, замолчать или исчезнуть", instead: "скажи спокойно и прямо: «мне это неприятно, давай обсудим»" },
  { group: "3", reaction: "хочется поучать", instead: "задай вопрос: «а как ты сам(а) это видишь?»" },
  { group: "4 · 7", reaction: "хочется всё бросить или сломать", instead: "доведи до конца одну маленькую задачу и заземлись" },
];

export function getProtocolStep3(id: number): ProtocolStep3 {
  if ([1, 8, 9].includes(id)) return PROTOCOL_STEP3[0];
  if ([2, 5, 6].includes(id)) return PROTOCOL_STEP3[1];
  if (id === 3) return PROTOCOL_STEP3[2];
  return PROTOCOL_STEP3[3];
}
